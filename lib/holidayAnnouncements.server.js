import { createHash } from 'node:crypto'
import { collectFirestorePages } from '@/lib/platform/firestoreQueries.server'
import { financeFilter as filter } from '@/lib/finance.server'
import { managesPolicies } from '@/lib/supportStore.server'

// Holidays coming up in the next few days get a ready-made announcement as a DRAFT.
// Nothing reaches employees until HR/Admin reviews it and clicks Publish.

export const HOLIDAY_ANNOUNCEMENT_LOOKAHEAD_DAYS = 7
const DAY_MS = 24 * 60 * 60 * 1000
const TIME_ZONE = 'Asia/Kolkata'

const istDateKey = value => new Date(value).toLocaleDateString('en-CA', { timeZone: TIME_ZONE })
const longDate = value => new Date(value).toLocaleDateString('en-IN', { timeZone: TIME_ZONE, weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' })
const portionText = holiday => holiday.dayPortion === 'first_half' ? ' (first half)' : holiday.dayPortion === 'second_half' ? ' (second half)' : ''

/** Same holiday and date always map to the same announcement, so a draft is never duplicated. */
export const holidayAnnouncementId = (holidayId, dateKey) =>
  createHash('sha1').update(`holiday-announcement:${holidayId}:${dateKey}`).digest('hex').slice(0, 24)

export function buildHolidayAnnouncementDraft(holiday, id, now = new Date()) {
  const from = new Date(holiday.date)
  const to = holiday.endDate && istDateKey(holiday.endDate) !== istDateKey(from) ? new Date(holiday.endDate) : null
  const when = to ? `from ${longDate(from)} to ${longDate(to)}` : `on ${longDate(from)}${portionText(holiday)}`
  const expiry = new Date(new Date(to || from).getTime() + DAY_MS)
  return {
    _id: id,
    title: `Holiday: ${holiday.name}`,
    content: `Dear Team,\n\nThe office will remain closed ${when} on account of ${holiday.name}.\n\nWishing you and your family a happy ${holiday.name}!\n\nRegards,\nHR Team`,
    status: 'draft',
    priority: 'medium',
    type: 'general',
    category: 'holiday',
    tags: ['holiday'],
    targetAudience: 'all',
    isDepartmentAnnouncement: false,
    views: [],
    engagement: { totalViews: 0 },
    expiryDate: expiry,
    sourceHolidayId: String(holiday._id),
    autoGenerated: true,
    createdBy: null,
    createdByRole: 'hr',
    createdAt: now,
    updatedAt: now,
  }
}

/**
 * Creates draft announcements for active holidays in the next 7 days (India time).
 * Runs for HR/Admin only. Each holiday date gets one draft; if HR deletes it, it is not recreated.
 */
export async function ensureHolidayAnnouncementDrafts({ database, actor, now = new Date() }) {
  if (!actor || !managesPolicies(actor)) return { created: 0 }
  const todayStart = new Date(`${istDateKey(now)}T00:00:00+05:30`)
  const until = new Date(todayStart.getTime() + (HOLIDAY_ANNOUNCEMENT_LOOKAHEAD_DAYS + 1) * DAY_MS - 1)
  const holidays = await collectFirestorePages(database, 'holidays', {
    filters: [filter('isActive', true), filter('date', todayStart, '>='), filter('date', until, '<=')],
    orderBy: [{ field: 'date', direction: 'asc' }],
  })
  let created = 0
  for (const holiday of holidays) {
    const dateKey = istDateKey(holiday.date)
    if (holiday.announcementDraftFor === dateKey) continue
    const id = holidayAnnouncementId(holiday._id, dateKey)
    const made = await database.transaction(async tx => {
      const current = await tx.get('holidays', String(holiday._id))
      if (!current || current.isActive === false || current.announcementDraftFor === istDateKey(current.date)) return false
      if (!await tx.get('announcements', id)) await tx.create('announcements', buildHolidayAnnouncementDraft(current, id, now))
      await tx.replace('holidays', { ...current, announcementDraftFor: istDateKey(current.date) })
      return true
    })
    if (made) created += 1
  }
  return { created }
}

/** Daily dashboard card for HR/Admin when holiday announcement drafts are waiting for review. */
export async function ensureHolidayAnnouncementReminder({ database, communications, user, now = new Date(), createCard }) {
  if (!user || !managesPolicies(user)) return
  const userId = String(user._id || user.userId || user.id), key = `holiday-announcements:${istDateKey(now)}`
  const id = createHash('sha256').update(`${userId}:${key}`).digest('hex').slice(0, 24)
  // One card per HR per day; later opens skip the holiday read entirely.
  if (await database.get('actionablenotifications', id)) return
  await ensureHolidayAnnouncementDrafts({ database: communications, actor: user, now })
  const drafts = (await collectFirestorePages(communications, 'announcements', { filters: [filter('status', 'draft')] }))
    .filter(row => row.autoGenerated && row.sourceHolidayId && !(row.expiryDate && +new Date(row.expiryDate) < +now))
  if (!drafts.length) return
  await database.transaction(async tx => {
    if (await tx.get('actionablenotifications', id)) return
    await tx.create('actionablenotifications', createCard({
      _id: id, user: userId, title: `Holiday announcement${drafts.length > 1 ? 's' : ''} to review (${drafts.length})`, type: 'generic', priority: 'medium',
      message: `${drafts.map(row => row.title).join('\n')}\nReview the text and click Publish to send it to everyone.`,
      url: '/dashboard/announcements', metadata: { reminderKey: key },
      displaySettings: { persistent: true, showInBell: true, playSound: false, dismissible: true },
    }))
  })
}
