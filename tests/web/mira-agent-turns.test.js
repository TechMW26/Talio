import { createMiraVoiceTurns, createMiraAcknowledgementCadence, miraListeningWord } from '@/lib/miraVoiceTurns'

test('repeated client tool calls never duplicate actions', async () => {
  const turns = createMiraVoiceTurns(), execute = jest.fn(async () => 'done')
  turns.transcript('Create a task', 1)
  const a = turns.execute({ message: 'Create a task', utterance_id: 'turn1' }, execute)
  const b = turns.execute({ message: 'Create a task', utterance_id: 'turn2' }, execute)
  expect(await a).toBe('done'); expect(await b).toBe('done'); expect(execute).toHaveBeenCalledTimes(1)
  turns.transcript('Create a task', 1)
  await turns.execute({ message: 'Create a task', utterance_id: 'turn3' }, execute)
  expect(execute).toHaveBeenCalledTimes(1)
  turns.transcript('Create a task', 2)
  await turns.execute({ message: 'Create a task', utterance_id: 'turn4' }, execute)
  expect(execute).toHaveBeenCalledTimes(2)
})
test('rejects unobserved, changed and partial utterances', () => {
  const turns = createMiraVoiceTurns(), execute = jest.fn()
  expect(() => turns.execute({ message: 'Send mail', utterance_id: 'one' }, execute)).toThrow()
  turns.transcript('Send mail to Alice', 1)
  expect(() => turns.execute({ message: 'Send mail', utterance_id: 'one' }, execute)).toThrow()
  expect(execute).not.toHaveBeenCalled()
})
test('listening acknowledgements are sparse and never run during response or short speech', () => {
  const cadence = createMiraAcknowledgementCadence()
  expect(cadence.sample(0.9, 0, true)).toBe(false)
  expect(cadence.sample(0.9, 5999, true)).toBe(false)
  expect(cadence.sample(0.9, 6000, true)).toBe(true)
  expect(cadence.sample(0.9, 26000, true)).toBe(false)
  cadence.newTurn()
  expect(cadence.sample(0.9, 27000, false)).toBe(false)
  expect(cadence.sample(0.9, 28000, true)).toBe(false)
  expect(cadence.sample(0.9, 34000, true)).toBe(true)
})
test('uses language-neutral acknowledgements unless clear Hinglish cues exist', () => {
  expect(miraListeningWord('mujhe ek task karna hai')).toBe('Achha.')
  expect(miraListeningWord('Tell me something')).toBe('Hmm.')
  expect(miraListeningWord('Tell me something', 1)).toBe('Okay.')
  expect(miraListeningWord('mujhe ek task karna hai', 1)).toBe('Hmm.')
  expect(miraListeningWord('मला मदत करा')).toBe('Hmm.')
})
