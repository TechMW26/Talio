import { workflowStore } from '../helpers/firestoreWorkflowStore'
import { ensureHolidayAnnouncementDrafts, ensureHolidayAnnouncementReminder, holidayAnnouncementId, buildHolidayAnnouncementDraft } from '@/lib/holidayAnnouncements.server'

const NOW = new Date('2026-12-20T10:00:00+05:30')
const hr = { _id: 'u-hr', role: 'hr' }
const holiday = (id, date, extra = {}) => ({ _id: id, name: 'Christmas', date: new Date(date), isActive: true, applicableTo: 'all', ...extra })

describe('holiday announcement drafts', () => {
  test('creates one draft (not published) for holidays in the next 7 days only', async () => {
    const database = workflowStore({
      holidays: [holiday('h1', '2026-12-25T00:00:00Z'), holiday('h2', '2027-01-26T00:00:00Z', { name: 'Republic Day' }), holiday('h3', '2026-12-22T00:00:00Z', { isActive: false })],
      announcements: [],
    })
    expect(await ensureHolidayAnnouncementDrafts({ database, actor: hr, now: NOW })).toEqual({ created: 1 })
    const [draft] = (await database.list('announcements')).records
    expect(draft).toMatchObject({ _id: holidayAnnouncementId('h1', '2026-12-25'), status: 'draft', title: 'Holiday: Christmas', sourceHolidayId: 'h1', autoGenerated: true, targetAudience: 'all' })
    expect(draft.content).toContain('Friday, 25 December 2026')
    expect(draft.expiryDate.toISOString()).toBe('2026-12-26T00:00:00.000Z')
  })

  test('does not duplicate, and does not recreate a draft HR discarded', async () => {
    const database = workflowStore({ holidays: [holiday('h1', '2026-12-25T00:00:00Z')], announcements: [] })
    await ensureHolidayAnnouncementDrafts({ database, actor: hr, now: NOW })
    expect(await ensureHolidayAnnouncementDrafts({ database, actor: hr, now: NOW })).toEqual({ created: 0 })
    await database.transaction(tx => tx.delete('announcements', holidayAnnouncementId('h1', '2026-12-25')))
    expect(await ensureHolidayAnnouncementDrafts({ database, actor: hr, now: NOW })).toEqual({ created: 0 })
    expect((await database.list('announcements')).records).toHaveLength(0)
  })

  test('a moved holiday gets a fresh draft for the new date', async () => {
    const database = workflowStore({ holidays: [holiday('h1', '2026-12-25T00:00:00Z')], announcements: [] })
    await ensureHolidayAnnouncementDrafts({ database, actor: hr, now: NOW })
    await database.mutate('holidays', 'h1', row => ({ ...row, date: new Date('2026-12-24T00:00:00Z') }))
    expect(await ensureHolidayAnnouncementDrafts({ database, actor: hr, now: NOW })).toEqual({ created: 1 })
  })

  test('employees and managers never trigger drafts', async () => {
    const database = workflowStore({ holidays: [holiday('h1', '2026-12-25T00:00:00Z')], announcements: [] })
    expect(await ensureHolidayAnnouncementDrafts({ database, actor: { role: 'employee' }, now: NOW })).toEqual({ created: 0 })
    expect(await ensureHolidayAnnouncementDrafts({ database, actor: { role: 'manager' }, now: NOW })).toEqual({ created: 0 })
    expect((await database.list('announcements')).records).toHaveLength(0)
  })

  test('multi-day and half-day holidays read correctly', () => {
    const multi = buildHolidayAnnouncementDraft(holiday('h1', '2026-10-20T00:00:00Z', { name: 'Diwali', endDate: new Date('2026-10-22T00:00:00Z') }), 'x', NOW)
    expect(multi.content).toContain('from Tuesday, 20 October 2026 to Thursday, 22 October 2026')
    const half = buildHolidayAnnouncementDraft(holiday('h1', '2026-10-20T00:00:00Z', { name: 'Holi', dayPortion: 'second_half' }), 'x', NOW)
    expect(half.content).toContain('(second half)')
  })

  test('HR gets one review card per day while drafts are waiting', async () => {
    const communications = workflowStore({ holidays: [holiday('h1', '2026-12-25T00:00:00Z')], announcements: [] })
    const database = workflowStore({ actionablenotifications: [] })
    const createCard = card => card
    await ensureHolidayAnnouncementReminder({ database, communications, user: hr, now: NOW, createCard })
    await ensureHolidayAnnouncementReminder({ database, communications, user: hr, now: NOW, createCard })
    const cards = (await database.list('actionablenotifications')).records
    expect(cards).toHaveLength(1)
    expect(cards[0]).toMatchObject({ title: 'Holiday announcement to review (1)', url: '/dashboard/announcements', user: 'u-hr' })
    await ensureHolidayAnnouncementReminder({ database, communications, user: { _id: 'u-emp', role: 'employee' }, now: NOW, createCard })
    expect((await database.list('actionablenotifications')).records).toHaveLength(1)
  })
})
