const { EventEmitter } = require('events')
const { manageRendererPerformance } = require('../../desktop-app/src/rendererPerformance')
test.each(['darwin', 'win32', 'linux'])('%s idle renderer throttles without suspending active voice or tasks', platform => {
  jest.useFakeTimers()
  const contents = Object.assign(new EventEmitter(), { isDestroyed: () => false, setBackgroundThrottling: jest.fn() })
  try {
    const policy = manageRendererPerformance(contents)
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(true)
    policy.set('voice', true)
    policy.set('desktop', true, 310000)
    policy.set('voice', false)
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(false)
    jest.advanceTimersByTime(310000)
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(true)
    contents.emit('media-started-playing')
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(false)
    contents.emit('media-paused')
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(true)
    policy.set('voice', true)
    contents.emit('did-start-navigation', {}, 'url', true, true)
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(false)
    contents.emit('did-start-navigation', {}, 'url', false, true)
    expect(contents.setBackgroundThrottling).toHaveBeenLastCalledWith(true)
    contents.emit('destroyed')
    expect(jest.getTimerCount()).toBe(0)
  } finally { jest.useRealTimers() }
})
