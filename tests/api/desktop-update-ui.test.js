const fs = require('fs')
const { JSDOM } = require('jsdom')
let dom, win, doc
const send = data => win.dispatchEvent(new win.MessageEvent('message', { data, source: win }))
const get = id => doc.getElementById(id)
beforeEach(() => {
  dom = new JSDOM(fs.readFileSync('desktop-app/src/update.html', 'utf8'), { runScripts: 'dangerously', url: 'file:///Talio/update.html' })
  win = dom.window; doc = win.document
})
afterEach(() => dom.window.close())
test('Quiet Focus starts with honest empty values and uses no external assets', () => {
  expect(get('title').textContent).toBe('Making room for better.')
  expect(get('versionRow').hidden).toBe(true)
  expect(get('progressBar').getAttribute('aria-valuenow')).toBe('0')
  expect(doc.querySelectorAll('script[src],link[href],img[src]').length).toBe(0)
})
test('uses the actual offline Talio logo from the desktop loader, not a typed wordmark', () => {
  const loader = new JSDOM(fs.readFileSync('desktop-app/src/loader.html', 'utf8'))
  const logo = doc.querySelector('header svg[aria-label="Talio"]')
  expect(logo).not.toBeNull()
  expect(logo.getAttribute('viewBox')).toBe(loader.window.document.querySelector('svg').getAttribute('viewBox'))
  expect(logo.querySelector('path').getAttribute('d')).toBe(loader.window.document.querySelector('svg path').getAttribute('d'))
  expect(logo.querySelector('path').getAttribute('fill')).toBe('#7DBCAF')
  expect(doc.querySelector('.wordmark')).toBeNull()
  loader.window.close()
})
test('shows actual versions, download percentage, byte counts and throughput', () => {
  send({ type: 'update-versions', current: '6.0.30', latest: '6.0.31' })
  send({ type: 'update-progress', percent: 42.2, transferred: 1048576, total: 2097152, bytesPerSecond: 2048 })
  expect(get('versionRow').hidden).toBe(false)
  expect(get('newVer').textContent).toBe('v6.0.31')
  expect(get('progressValue').textContent).toBe('42')
  expect(get('progressBar').style.getPropertyValue('--progress')).toBe('42%')
  expect(get('progressDetail').textContent).toBe('1.0 MB / 2.0 MB · 2.0 KB/s')
})
test.each([[150,100],[-20,0],[NaN,0],[Infinity,0]])('clamps invalid progress %s to %s', (input, expected) => {
  send({ type:'update-progress',percent:input })
  expect(get('progressBar').getAttribute('aria-valuenow')).toBe(String(expected))
})
test('all verification/install/completion states are wired without a fake timer', () => {
  send({ type:'update-verifying' })
  expect(get('step2').getAttribute('aria-current')).toBe('step')
  expect(get('title').textContent).toBe('A quick final check.')
  send({ type:'update-downloaded' })
  expect(doc.body.dataset.state).toBe('downloaded')
  send({ type:'update-installing' })
  expect(get('step3').getAttribute('aria-current')).toBe('step')
  send({ type:'update-complete' })
  expect(doc.body.dataset.state).toBe('complete')
  expect(get('progressValue').textContent).toBe('✓')
  expect(get('progressUnit').hidden).toBe(true)
  expect(doc.querySelectorAll('.step.done')).toHaveLength(3)
  send({ type:'update-progress',percent:3 })
  expect(doc.body.dataset.state).toBe('complete')
})
test('retry restores the initial view and invokes the real update bridge', async () => {
  win.electronAPI = { retryUpdate: jest.fn(async () => {}) }
  send({ type:'update-error',message:'Network unavailable' })
  expect(get('errorMsg').textContent).toBe('Network unavailable')
  expect(get('retryBtn').hidden).toBe(false)
  get('retryBtn').click()
  await new Promise(setImmediate)
  expect(win.electronAPI.retryUpdate).toHaveBeenCalledTimes(1)
  expect(get('errorMsg').hidden).toBe(true)
  expect(doc.body.dataset.state).toBe('preparing')
  expect(get('step1').getAttribute('aria-current')).toBe('step')
})
test('IPC failure leaves an actionable retry, not a stuck preparing view', async () => {
  win.electronAPI = { retryUpdate: jest.fn(async () => { throw Error('Could not restart download') }) }
  send({ type:'update-error' })
  get('retryBtn').click()
  await new Promise(setImmediate)
  expect(get('errorMsg').textContent).toBe('Could not restart download')
  expect(get('retryBtn').hidden).toBe(false)
  expect(get('retryBtn').disabled).toBe(false)
})
test('renders incoming strings as text and ignores another window', () => {
  send({ type:'update-error',message:'<img src=x onerror=alert(1)>' })
  expect(get('errorMsg').querySelector('img')).toBeNull()
  win.dispatchEvent(new win.MessageEvent('message', { data:{type:'update-complete'}, source:{} }))
  expect(doc.body.dataset.state).toBe('error')
})
